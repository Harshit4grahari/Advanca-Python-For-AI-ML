#Variables in Python
#Variables are used to store data in a program. In Python, you can create a variable by simply assigning a value to a name. For example:

x = 5 #integer variable
y = "Hello, World!" #string variable
_is_code = True #boolean variable
print(x)
print(y)
print(_is_code)
print(f" this is the simple text: {_is_code}, {y}") # f string is used to format the string with variables

#Rules for naming variables in Python:
#1. Variable names must start with a letter or an underscore (_).
#2. Variable names cannot contain spaces.
#3. Variable names are case-sensitive.
#4. Variable names cannot be Python keywords.