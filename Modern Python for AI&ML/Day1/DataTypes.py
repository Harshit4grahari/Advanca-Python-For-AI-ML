#DataTypes in Python
#Python has several built-in data types that are used to define the kind of value a variable can hold. Some of the most common data types are:

#1. Integer (int): Represents whole numbers.
x = 5
print(x)

#2. Float: Represents decimal numbers.
y = 3.14
print(y)

#3. String (str): Represents a sequence of characters.
z = "Hello, World!"
print(z)

#4. Boolean (bool): Represents either True or False.
is_true = True
is_false = False
print(is_true)
print(is_false)


#Check Type using type() function
print(type(x)) # <class 'int'>
print(type(y)) # <class 'float'>
print(type(z)) # <class 'str'>
print(type(is_true)) # <class 'bool'>