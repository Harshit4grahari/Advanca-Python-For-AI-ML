# LOOPS in Python:
# Loops are used to repeat a block of code multiples times.Python provides two types of loops: for and while loops.

# For Loop: (start, stop, step)
for i in range(5):
    print("Hi") 

for i in range(5):
    print(i)

# real Life Example:
email = ["agha@gmail.com", "rwyuqh@gmail.com", "qysh@gmail.com", "znxjs@gmail.com"]
for i in email:
    print("Send Email to ", i)


# While Loop:
i = 0
while i < 5:
    print(i)
    i= i+1