# Tuples in Python:
# A tuples is a built-in datatype that lets us create immutable sequence of values.(Once Created then can't be modify)

# Example of Tuples:
my_tuple = (12,21,1113,4432,12)
print(my_tuple)

# Tuples vs List
# Features         Tuple                  List
# Syntax           () Parantheses         [] Square Bracket
# Mutable?         NO (can't be modify)   Yes (can be modify
# Allow Duplicate  Yes                    No

my_tuple = (1, 2, 1, 3, 1, 4)

print(my_tuple.index(1))
print(my_tuple.count(1))